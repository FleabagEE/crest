"""Generate ``sketches/common/crest_logmel_tables.h`` for the integer log-mel front end.

The tables reproduce the course-project training front end
(``embedded-systme-project/training/features.py``, ``log_mel``):

- 16 kHz audio, 400-sample frames (25 ms), hop 160 (10 ms), no centering;
- periodic Hann of 400 samples (``np.hanning(401)[:-1]``);
- 512-point real FFT (frame right-zero-padded), power spectrum;
- 64 mel bins from ``librosa.filters.mel(sr=16000, n_fft=512, n_mels=64,
  fmin=0, fmax=8000, htk=False, norm='slaney')``;
- natural log of ``max(mel, 1e-6)``.

Quantization (all integer on the device):

- Hann: uint16 Q16 (``round(w * 65536)``, clamped to 65535).
- Mel matrix: stored sparse, one contiguous run of nonzero FFT bins per mel
  bin, as uint16 ``round(w / mel_scale)`` with one global
  ``mel_scale = max(w) / 65535``. ``log2(mel_scale)`` is stored in Q16.
- ``log2(1 + i/256)`` for i = 0..256 in Q16, for the fixed-point logarithm.

Run with the ``crest`` env (librosa 0.11.0, numpy 1.26.4, the versions in
the training repo's requirements lock).
"""

from __future__ import annotations

import argparse
import math
from pathlib import Path

import librosa
import numpy as np

SCRIPT_DIR = Path(__file__).resolve().parent
REPO_ROOT = SCRIPT_DIR.parents[1]
DEFAULT_OUTPUT = REPO_ROOT / "sketches" / "common" / "crest_logmel_tables.h"

SAMPLE_RATE = 16000
FRAME_LENGTH = 400
HOP_LENGTH = 160
FFT_LENGTH = 512
N_MELS = 64
LOG_OFFSET = 1e-6
LOG2_LUT_BITS = 8


def hann_q16() -> np.ndarray:
    """Periodic Hann window as uint16 Q16 (exact training definition)."""
    window = np.hanning(FRAME_LENGTH + 1)[:-1].astype(np.float32).astype(np.float64)
    return np.minimum(np.round(window * 65536.0), 65535).astype(np.uint16)


def mel_matrix() -> np.ndarray:
    """``(N_MELS, FFT_LENGTH // 2 + 1)`` float32 Slaney mel weights, as in training."""
    return librosa.filters.mel(
        sr=SAMPLE_RATE, n_fft=FFT_LENGTH, n_mels=N_MELS, fmin=0, fmax=SAMPLE_RATE / 2, htk=False, norm="slaney"
    ).astype(np.float32)


def sparse_mel(weights: np.ndarray):
    """Return ``(starts, lengths, offsets, values_u16, mel_scale)`` for the matrix."""
    mel_scale = float(weights.max()) / 65535.0
    starts, lengths, offsets, values = [], [], [], []
    for row in weights:
        nonzero = np.flatnonzero(row > 0)
        if nonzero.size == 0:
            raise ValueError("empty mel bin")
        start, stop = int(nonzero[0]), int(nonzero[-1]) + 1
        if not np.all(row[start:stop] > 0):
            raise ValueError("mel bin support is not contiguous")
        starts.append(start)
        lengths.append(stop - start)
        offsets.append(len(values))
        values.extend(np.round(row[start:stop].astype(np.float64) / mel_scale).astype(np.int64).tolist())
    return starts, lengths, offsets, np.array(values, dtype=np.int64), mel_scale


def log2_lut_q16() -> np.ndarray:
    """``round(log2(1 + i / 256) * 65536)`` for i = 0..256."""
    i = np.arange((1 << LOG2_LUT_BITS) + 1, dtype=np.float64)
    return np.round(np.log2(1.0 + i / (1 << LOG2_LUT_BITS)) * 65536.0).astype(np.int64)


def c_array(ctype: str, name: str, values, per_line: int = 12) -> str:
    """Format a C array definition."""
    items = [str(int(v)) for v in values]
    lines = [", ".join(items[i:i + per_line]) for i in range(0, len(items), per_line)]
    body = ",\n  ".join(lines)
    return f"static const {ctype} {name}[{len(items)}] = {{\n  {body}\n}};\n"


def render(weights: np.ndarray) -> str:
    """Render the header text."""
    starts, lengths, offsets, values, mel_scale = sparse_mel(weights)
    if values.max() > 65535 or values.min() < 0:
        raise ValueError("mel weights out of uint16 range")
    log2_mel_scale_q16 = int(round(math.log2(mel_scale) * 65536.0))
    ln_floor_q16 = int(round(math.log(LOG_OFFSET) * 65536.0))
    parts = [
        "// Copyright (c) 2026 UCLA Networked & Embedded Systems Laboratory",
        "// SPDX-License-Identifier: BSD-3-Clause",
        "// GENERATED by analysis_scripts/rp2040_logmel/export_logmel_tables.py; do not edit.",
        f"// librosa {librosa.__version__}, numpy {np.__version__}.",
        "// Training front end: 16 kHz, frame 400, hop 160, periodic Hann, 512-pt rfft power,",
        "// 64 Slaney mel bins (fmin 0, fmax 8000, norm='slaney'), ln(max(mel, 1e-6)).",
        "#pragma once",
        "#include <stdint.h>",
        "",
        f"#define CREST_LOGMEL_SAMPLE_RATE {SAMPLE_RATE}",
        f"#define CREST_LOGMEL_FRAME_LENGTH {FRAME_LENGTH}",
        f"#define CREST_LOGMEL_HOP_LENGTH {HOP_LENGTH}",
        f"#define CREST_LOGMEL_FFT_LENGTH {FFT_LENGTH}",
        f"#define CREST_LOGMEL_NUM_BINS {FFT_LENGTH // 2 + 1}",
        f"#define CREST_LOGMEL_NUM_MELS {N_MELS}",
        f"#define CREST_LOGMEL_LOG2_LUT_BITS {LOG2_LUT_BITS}",
        f"// mel_scale = {mel_scale!r}; weight = value * mel_scale",
        f"#define CREST_LOGMEL_LOG2_MEL_SCALE_Q16 ({log2_mel_scale_q16})",
        f"// ln(1e-6) in Q16",
        f"#define CREST_LOGMEL_LN_FLOOR_Q16 ({ln_floor_q16})",
        "",
        c_array("uint16_t", "kCrestLogmelHannQ16", hann_q16()),
        c_array("uint16_t", "kCrestLogmelMelStart", starts),
        c_array("uint16_t", "kCrestLogmelMelLength", lengths),
        c_array("uint16_t", "kCrestLogmelMelOffset", offsets),
        c_array("uint16_t", "kCrestLogmelMelWeight", values),
        c_array("uint32_t", "kCrestLogmelLog2LutQ16", log2_lut_q16()),
    ]
    return "\n".join(parts)


def main() -> int:
    """Write the header."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args()
    weights = mel_matrix()
    args.output.write_text(render(weights), encoding="utf-8")
    nnz = int((weights > 0).sum())
    print(f"wrote {args.output} ({nnz} nonzero mel weights, max {weights.max():.6g})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
